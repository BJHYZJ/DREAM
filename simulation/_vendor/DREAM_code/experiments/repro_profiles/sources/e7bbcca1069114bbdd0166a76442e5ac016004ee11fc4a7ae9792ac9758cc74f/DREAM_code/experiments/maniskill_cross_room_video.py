from houseexpo_cross_room import ensure_houseexpo, make_scenario, run_scenario


QUALITATIVE_BOUNDARY = (
    "Kinematic replay of a DREAM planner trajectory in ManiSkill/SAPIEN; "
    "not a closed-loop simulator benchmark or an additional success-rate trial."
)
WALL_COLOR = [0.74, 0.78, 0.82, 1.0]
FLOOR_COLOR = [0.91, 0.90, 0.86, 1.0]


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _read_rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as stream:
        return list(csv.DictReader(stream))


def select_replay(results_csv: Path) -> dict[str, str]:
    """Choose a successful, multi-room, visually non-trivial DREAM episode."""

    candidates = [
        row
        for row in _read_rows(results_csv)
        if row["policy"] == "dream"
        and int(row["success"]) == 1
        and row["scale"] in {"7--9 rooms", "10+ rooms"}
    ]
    if not candidates:
        raise RuntimeError("No successful 7+ room DREAM episode in episodes.csv")

    def score(row: dict[str, str]) -> tuple[float, ...]:
        path_m = float(row["path_m"])
        return (
            float(min(int(row["rooms_visited"]), 8)),
            float(row["scale"] == "10+ rooms"),
            -abs(path_m - 32.0),
            float(min(int(row["replans"]), 12)),
        )

    return max(candidates, key=score)


def _world(point: np.ndarray, center: np.ndarray, meters_per_cell: float) -> np.ndarray:
    """Convert image row/column coordinates to a right-handed XY world frame."""

    return np.asarray(
        [
            (float(point[1]) - center[1]) * meters_per_cell,
            (center[0] - float(point[0])) * meters_per_cell,
        ],
        dtype=np.float64,
    )


def _boundary_runs(free: np.ndarray) -> list[tuple[str, float, float, float]]:
    """Merge exposed grid-cell edges into axis-aligned wall runs."""

    horizontal: dict[float, list[tuple[float, float]]] = {}
    vertical: dict[float, list[tuple[float, float]]] = {}
    rows, cols = free.shape
    for row, col in np.column_stack(np.where(free)):
        if row == 0 or not free[row - 1, col]:
            horizontal.setdefault(row - 0.5, []).append((col - 0.5, col + 0.5))
        if row == rows - 1 or not free[row + 1, col]:
            horizontal.setdefault(row + 0.5, []).append((col - 0.5, col + 0.5))
        if col == 0 or not free[row, col - 1]:
            vertical.setdefault(col - 0.5, []).append((row - 0.5, row + 0.5))
        if col == cols - 1 or not free[row, col + 1]:
            vertical.setdefault(col + 0.5, []).append((row - 0.5, row + 0.5))

    output: list[tuple[str, float, float, float]] = []
    for orientation, groups in (("h", horizontal), ("v", vertical)):
        for fixed, intervals in groups.items():
            intervals.sort()
            run_start, run_end = intervals[0]
            for start, end in intervals[1:]:
                if start <= run_end + 1e-9:
                    run_end = max(run_end, end)
                else:
                    output.append((orientation, fixed, run_start, run_end))
                    run_start, run_end = start, end
            output.append((orientation, fixed, run_start, run_end))
    return output


def _uniform_frames(points: np.ndarray, frame_count: int) -> np.ndarray:
    """Resample a polyline by arc length while preserving planner geometry."""

    points = np.asarray(points, dtype=np.float64)
    if len(points) <= 1:
        return np.repeat(points, frame_count, axis=0)
    lengths = np.linalg.norm(np.diff(points, axis=0), axis=1)
    keep = np.concatenate(([True], lengths > 1e-12))
    points = points[keep]
    if len(points) <= 1:
        return np.repeat(points, frame_count, axis=0)
    lengths = np.linalg.norm(np.diff(points, axis=0), axis=1)
    cumulative = np.concatenate(([0.0], np.cumsum(lengths)))
    samples = np.linspace(0.0, cumulative[-1], frame_count)
    output = []
    for sample in samples:
        segment = min(int(np.searchsorted(cumulative, sample, side="right") - 1), len(lengths) - 1)
        local = (sample - cumulative[segment]) / lengths[segment]
        output.append(points[segment] + local * (points[segment + 1] - points[segment]))
    return np.asarray(output)


def _map_inset(
    free: np.ndarray,
    trajectory: np.ndarray,
    current_index: int,
    start: tuple[int, int],
    target: tuple[int, int],
    width: int,
) -> np.ndarray:
    canvas = np.full((*free.shape, 3), 238, dtype=np.uint8)
    canvas[~free] = (55, 61, 69)
    complete = np.rint(trajectory[: current_index + 1]).astype(np.int32)
    future = np.rint(trajectory[current_index:]).astype(np.int32)
    if len(future) > 1:
        cv2.polylines(canvas, [future[:, ::-1]], False, (165, 172, 178), 2, cv2.LINE_AA)
    if len(complete) > 1:
        cv2.polylines(canvas, [complete[:, ::-1]], False, (225, 145, 32), 3, cv2.LINE_AA)
    cv2.circle(canvas, (start[1], start[0]), 4, (85, 176, 108), -1, cv2.LINE_AA)
    cv2.drawMarker(canvas, (target[1], target[0]), (60, 60, 220), cv2.MARKER_STAR, 12, 2)
    current = complete[-1]
    cv2.circle(canvas, (int(current[1]), int(current[0])), 4, (15, 15, 15), -1, cv2.LINE_AA)
    height = max(1, int(round(canvas.shape[0] * width / canvas.shape[1])))
    return cv2.resize(canvas, (width, height), interpolation=cv2.INTER_NEAREST)


def _annotate(rgb: np.ndarray, scenario, trajectory: np.ndarray, frame_index: int, path_m: float) -> np.ndarray:
    frame = cv2.cvtColor(rgb, cv2.COLOR_RGB2BGR)
    overlay = frame.copy()
    cv2.rectangle(overlay, (0, 0), (frame.shape[1], 80), (18, 25, 31), -1)
    cv2.addWeighted(overlay, 0.80, frame, 0.20, 0, frame)
    cv2.putText(
        frame,
        "DREAM cross-room search | ManiSkill / SAPIEN Fetch replay",
        (22, 31),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.64,
        (255, 255, 255),
        2,
        cv2.LINE_AA,
    )
    cv2.putText(
        frame,
        f"HouseExpo {scenario.house_id[:12]} | {scenario.official_room_count} rooms | route {path_m:.1f} m",
        (22, 60),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.48,
        (202, 220, 229),
        1,
        cv2.LINE_AA,
    )
    inset = _map_inset(
        scenario.free,
        trajectory,
        frame_index,
        scenario.start,
        scenario.target,
        width=min(270, frame.shape[1] // 3),
    )
    margin = 16
    y0 = frame.shape[0] - inset.shape[0] - margin
    x0 = frame.shape[1] - inset.shape[1] - margin
    if y0 > 88:
        frame[y0 : y0 + inset.shape[0], x0 : x0 + inset.shape[1]] = inset
        cv2.rectangle(
            frame,
            (x0 - 2, y0 - 2),
            (x0 + inset.shape[1] + 1, y0 + inset.shape[0] + 1),
            (245, 245, 245),
            2,
        )
    cv2.putText(
        frame,
        "QUALITATIVE KINEMATIC REPLAY (not a closed-loop benchmark)",
        (18, frame.shape[0] - 16),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.38,
        (240, 240, 240),
        1,
        cv2.LINE_AA,
    )
    return cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)


def _build_scene(base, scenario, center: np.ndarray, meters_per_cell: float) -> int:
    rows, cols = scenario.free.shape
    floor_center = _world(np.asarray([(rows - 1) / 2, (cols - 1) / 2]), center, meters_per_cell)
    actors.build_box(
        base.scene,
        half_sizes=[cols * meters_per_cell / 2, rows * meters_per_cell / 2, 0.025],
        color=FLOOR_COLOR,
        name="houseexpo_floor",
        body_type="static",
        add_collision=False,
        initial_pose=sapien.Pose([floor_center[0], floor_center[1], 0.025]),
    )
    wall_height = 1.05
    wall_thickness = 0.065
    runs = _boundary_runs(scenario.free)
    for index, (orientation, fixed, start, end) in enumerate(runs):
        if orientation == "h":
            grid_center = np.asarray([fixed, (start + end) / 2])
            half_sizes = [(end - start) * meters_per_cell / 2, wall_thickness, wall_height / 2]
        else:
            grid_center = np.asarray([(start + end) / 2, fixed])
            half_sizes = [wall_thickness, (end - start) * meters_per_cell / 2, wall_height / 2]
        world_center = _world(grid_center, center, meters_per_cell)
        actors.build_box(
            base.scene,
            half_sizes=half_sizes,
            color=WALL_COLOR,
            name=f"houseexpo_wall_{index:04d}",
            body_type="static",
            add_collision=False,
            initial_pose=sapien.Pose([world_center[0], world_center[1], wall_height / 2]),
        )

    target_world = _world(np.asarray(scenario.target), center, meters_per_cell)
    actors.build_box(
        base.scene,
        half_sizes=[0.22, 0.22, 0.36],
        color=[0.83, 0.18, 0.20, 1.0],
        name="target_pedestal",
        body_type="static",
        add_collision=False,
        initial_pose=sapien.Pose([target_world[0], target_world[1], 0.36]),
    )
    actors.build_sphere(
        base.scene,
        radius=0.18,
        color=[1.0, 0.15, 0.12, 1.0],
        name="target_object",
        body_type="static",
        add_collision=False,
        initial_pose=sapien.Pose([target_world[0], target_world[1], 0.90]),
    )
    return len(runs)


def render(args: argparse.Namespace) -> None:
    args.output_root.mkdir(parents=True, exist_ok=True)
    selection = select_replay(args.results_csv)
    json_root, _ = ensure_houseexpo(args.data_root)
    scenario = make_scenario(
        json_root / f"{selection['house_id']}.json",
        selection["scale"],
        resolution=args.resolution,
        robot_radius=args.robot_radius,
        minimum_cross_room_m=args.minimum_cross_room,
    )
    result, trace = run_scenario(
        scenario,
        "dream",
        budget_m=float(selection["budget_m"]),
        sensor_range_m=args.sensor_range,
        semantic_rate=args.semantic_rate,
        keep_trace=True,
    )
    if not result.success or trace is None:
        raise RuntimeError("Selected DREAM episode did not reproduce as a success")

    trajectory = _uniform_frames(np.asarray(trace["trajectory"]), args.frames)
    center = np.mean(trajectory, axis=0)
    meters_per_cell = scenario.resolution_m * args.scene_scale
    world_trajectory = np.asarray([_world(point, center, meters_per_cell) for point in trajectory])

    env = gym.make(
        "Empty-v1",
        robot_uids="fetch",
        obs_mode="none",
        reward_mode="none",
        render_mode="rgb_array",
        sim_backend="physx_cpu",
        render_backend="cpu",
        num_envs=1,
        human_render_camera_configs=dict(
            width=args.width,
            height=args.height,
            fov=1.05,
            near=0.05,
            far=100,
            shader_pack="default",
        ),
    )
    env.reset(seed=0)
    base = env.unwrapped
    wall_count = _build_scene(base, scenario, center, meters_per_cell)
    qpos = base.agent.robot.get_qpos().clone()
    rest = np.asarray(base.agent.keyframes["rest"].qpos, dtype=np.float32)
    qpos[0, : len(rest)] = qpos.new_tensor(rest)

    frames: list[np.ndarray] = []
    camera = base._human_render_cameras["render_camera"].camera
    previous_yaw = 0.0
    for index, xy in enumerate(world_trajectory):
        direction = (
            world_trajectory[index + 1] - xy
            if index + 1 < len(world_trajectory)
            else xy - world_trajectory[index - 1]
        )
        if np.linalg.norm(direction) > 1e-8:
            desired_yaw = math.atan2(float(direction[1]), float(direction[0]))
            previous_yaw += math.atan2(
                math.sin(desired_yaw - previous_yaw), math.cos(desired_yaw - previous_yaw)
            )
        qpos[0, 0] = float(xy[0])
        qpos[0, 1] = float(xy[1])
        qpos[0, 2] = float(previous_yaw)
        base.agent.robot.set_qpos(qpos)

        heading = np.asarray([math.cos(previous_yaw), math.sin(previous_yaw)])
        side = np.asarray([-heading[1], heading[0]])
        eye_xy = xy - 4.4 * heading - 3.4 * side
        camera_pose = sapien_utils.look_at(
            [float(eye_xy[0]), float(eye_xy[1]), 4.2],
            [float(xy[0] + 0.8 * heading[0]), float(xy[1] + 0.8 * heading[1]), 0.55],
        )
        camera.set_local_pose(camera_pose.sp)
        raw = env.render()
        if hasattr(raw, "detach"):
            raw = raw.detach().cpu().numpy()
        rgb = np.asarray(raw)[0]
        if rgb.dtype != np.uint8:
            scale = 255.0 if float(rgb.max()) <= 1.0 else 1.0
            rgb = np.clip(rgb * scale, 0, 255).astype(np.uint8)
        frames.append(_annotate(rgb, scenario, trajectory, index, result.path_m))
        if (index + 1) % 24 == 0:
            print(f"Rendered {index + 1}/{len(world_trajectory)} frames", flush=True)

    env.close()
    video_path = args.output_root / "dream_cross_room_maniskill.mp4"
    with imageio.get_writer(
        video_path,
        fps=args.fps,
        codec="libx264",
        quality=8,
        macro_block_size=None,
        ffmpeg_log_level="warning",
    ) as writer:
        for frame in frames:
            writer.append_data(frame)

    montage_indices = np.linspace(0, len(frames) - 1, 4).astype(int)
    montage_frames = []
    for panel, frame_index in enumerate(montage_indices):
        frame = frames[frame_index].copy()
        cv2.putText(
            frame,
            f"({chr(ord('a') + panel)}) {100 * frame_index / max(len(frames) - 1, 1):.0f}% route",
            (18, 108),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.52,
            (255, 255, 255),
            2,
            cv2.LINE_AA,
        )
        montage_frames.append(frame)
    montage = np.vstack((np.hstack(montage_frames[:2]), np.hstack(montage_frames[2:])))
    montage_path = args.output_root / "dream_cross_room_montage.png"
    imageio.imwrite(montage_path, montage)

    metadata = {
        "evidence_type": "qualitative simulator visualization",
        "boundary": QUALITATIVE_BOUNDARY,
        "simulator": "ManiSkill 3.0.1 / SAPIEN 3.0.3",
        "robot": "Fetch embodiment distributed with ManiSkill",
        "simulation_backend": "PhysX CPU",
        "render_backend": "CPU Vulkan (lavapipe)",
        "source_floorplan": "HouseExpo official test split",
        "house_id": scenario.house_id,
        "official_rooms": scenario.official_room_count,
        "scale": scenario.scale,
        "success": result.success,
        "planner_path_m": result.path_m,
        "rooms_visited": result.rooms_visited,
        "replans": result.replans,
        "frames": len(frames),
        "fps": args.fps,
        "wall_segments": wall_count,
        "trajectory_source": str(args.results_csv),
        "trajectory_source_sha256": _sha256(args.results_csv),
        "video_sha256": _sha256(video_path),
        "montage_sha256": _sha256(montage_path),
        "selection_rule": "successful DREAM episode in 7+ room scale; prefer up to 8 rooms visited and route near 32 m",
    }
    (args.output_root / "metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    print(json.dumps(metadata, indent=2), flush=True)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--results-csv",
        type=Path,
        default=Path("experiments/results/houseexpo_cross_room/episodes.csv"),
    )
    parser.add_argument("--data-root", type=Path, default=Path("experiments/data/houseexpo"))
    parser.add_argument(
        "--output-root", type=Path, default=Path("experiments/results/maniskill_cross_room")
    )
    parser.add_argument("--resolution", type=float, default=0.25)
    parser.add_argument("--robot-radius", type=float, default=0.20)
    parser.add_argument("--sensor-range", type=float, default=2.5)
    parser.add_argument("--minimum-cross-room", type=float, default=6.0)
    parser.add_argument("--semantic-rate", type=float, default=0.1)
    parser.add_argument("--scene-scale", type=float, default=1.35)
    parser.add_argument("--frames", type=int, default=96)
    parser.add_argument("--fps", type=int, default=12)
    parser.add_argument("--width", type=int, default=960)
    parser.add_argument("--height", type=int, default=540)
    args = parser.parse_args()
    os.environ.setdefault("MS_SKIP_ASSET_DOWNLOAD_PROMPT", "1")
    render(args)


if __name__ == "__main__":
    main()
