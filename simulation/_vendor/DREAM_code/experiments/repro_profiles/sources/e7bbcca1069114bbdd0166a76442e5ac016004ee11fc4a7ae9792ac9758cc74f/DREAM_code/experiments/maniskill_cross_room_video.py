#!/usr/bin/env python3
"""Render a DREAM cross-room trajectory with the ManiSkill/SAPIEN Fetch robot.

This program is intentionally a *qualitative kinematic replay*. The trajectory
is generated by ``houseexpo_cross_room.py`` in a public HouseExpo layout and
then replayed using ManiSkill's Fetch embodiment. It is not a new closed-loop
simulator benchmark or learned-perception experiment.
"""

from __future__ import annotations

